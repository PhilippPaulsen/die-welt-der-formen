    md`#### General
  The regular polygons possess, besides their mirror lines, also a center of rotation, lying at the center of the polygon, about which there exists a rotation as many-fold as the polygon has corners or sides. Accordingly, the triangle is, to begin with, a three-fold rotational form.

  One can now, just as before, choose, in a triangle composed of *n²* sub-triangles, a node line as theme, and develop it into a pattern, with the difference that, instead of reflection, rotation is put into operation. The theme thereby comes into two further positions, so that a form of three lines arises, which is repeated as usual, and thus fills an unlimited plane with its pattern.

  These three lines form a rotational form. In general, the same form arises from the corresponding mirror pair, if one omits, in the latter, every other line of the six of which it consists. If the mirror pair has, owing to a symmetric position of the theme, only three lines, it is not different from the rotational form.

  The omission of every other line can take place in two ways. Two rotational forms arise thereby, which are mirror-equal. One must not suppose that one obtains these two patterns by rotating the theme once to the right and once to the left; in that way, only equal forms arise. Rather, the second form arises from a different node line, which is mirror-equal to the first. Since, however, both forms are equal apart from their sense of rotation, they are not both depicted, but only one of them. If one wishes to see, along with it, the second, mirror-equal form, one need only turn the sheet over. This saves almost half the drawings. In the case where the theme itself lies symmetrically, so that the corresponding mirror pair has only three lines and is equal to the corresponding rotational form, the latter shows no sense of rotation. In that case, too, there is no opposite form, since the theme coincides with its own mirror image.`
