/**
 * tools/build-start.cjs (task 171). The gallery of the two start pages (index_d.html DE, index.html EN) from studio/presets/manifest.json (the synced copy of the generator's manifest).
 *   node tools/build-start.cjs [--check]      writes the block between <!-- gallery:begin ... --> and <!-- gallery:end -->; --check only compares (exit 1 on a difference)
 * Static HTML, committed (GitHub Pages does not build): complete and readable without JavaScript (the five slides under each other), the first image not lazy. Order, captions, alt texts and image
 * names come from the manifest's `gallery` blocks (task 169); the image files are assets/presets/<image>. A new exhibit is a manifest entry, a new image file and a run of this script.
 */
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..');
const esc = s => String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

const TEXT = {
    de: { page: 'index_d.html', region: 'Beispiele aus dem Studio, von einfach zu komplex', strip: 'Bilder, mit den Pfeiltasten links und rechts wechseln', slide: (i, n) => `${i} von ${n}`, frame: c => `Preset im Studio öffnen: ${c}`, open: 'Preset im Studio öffnen' },
    en: { page: 'index.html', region: 'Examples from the Studio, from simple to complex', strip: 'Images, switch with the left and right arrow keys', slide: (i, n) => `${i} of ${n}`, frame: c => `Open preset in the Studio: ${c}`, open: 'Open preset in the Studio' },
};
const OPEN_ICON = '<svg class="ico" viewBox="0 0 24 24" aria-hidden="true"><path d="M10 5 H5 V19 H19 V14"/><path d="M14 5 H19 V10"/><path d="M19 5 L11 13"/></svg>';

function exhibits() {
    const man = JSON.parse(fs.readFileSync(path.join(ROOT, 'studio', 'presets', 'manifest.json'), 'utf8'));
    const list = man.presets.filter(p => p.gallery).sort((a, b) => a.gallery.order - b.gallery.order);
    list.forEach((p, i) => {
        if (p.gallery.order !== i + 1) throw new Error(`gallery order of ${p.slug} is ${p.gallery.order}, expected ${i + 1}`);
        if (!p.listed) throw new Error(`${p.slug} is in the gallery but not listed`);
        if (!fs.existsSync(path.join(ROOT, 'assets', 'presets', p.gallery.image))) throw new Error(`image assets/presets/${p.gallery.image} is missing`);
    });
    return list;
}

function galleryHtml(lang, list) {
    const T = TEXT[lang], n = list.length;
    const slides = list.map((p, i) => {
        const g = p.gallery, cap = g.caption[lang], href = `p/${p.slug}/?lang=${lang}`;
        return `      <figure class="g-slide" id="g${i + 1}" data-href="${href}" aria-roledescription="${lang === 'de' ? 'Folie' : 'slide'}" aria-label="${T.slide(i + 1, n)}">
        <a class="g-frame" href="${href}" aria-label="${esc(T.frame(cap))}"><img src="assets/presets/${esc(g.image)}" alt="${esc(g.alt[lang])}" width="600" height="600"${i ? ' loading="lazy"' : ''}></a>
        <figcaption><span>${esc(cap)}</span><a class="icon-btn g-open" href="${href}" aria-label="${T.open}" title="${T.open}">${OPEN_ICON}</a></figcaption>
      </figure>`;
    }).join('\n');
    return `    <section class="gallery" aria-roledescription="${lang === 'de' ? 'Karussell' : 'carousel'}" aria-label="${T.region}">
      <div class="g-viewport" tabindex="0" role="group" aria-label="${T.strip}">
${slides}
      </div>
    </section>`;
}

const BEGIN = '<!-- gallery:begin (generated by tools/build-start.cjs from studio/presets/manifest.json; do not edit) -->', END = '<!-- gallery:end -->';
function build() {
    const list = exhibits(), out = {};
    for (const lang of ['de', 'en']) {
        const f = TEXT[lang].page, s = fs.readFileSync(path.join(ROOT, f), 'utf8');
        const a = s.indexOf(BEGIN), b = s.indexOf(END);
        if (a < 0 || b < a) throw new Error(`${f}: the gallery markers are missing`);
        out[f] = s.slice(0, a) + BEGIN + '\n' + galleryHtml(lang, list) + '\n    ' + s.slice(b);
    }
    return out;
}
module.exports = { build, galleryHtml, exhibits, TEXT, BEGIN, END };

if (require.main === module) {
    const check = process.argv.includes('--check');
    const out = build();
    let diff = 0;
    for (const [f, t] of Object.entries(out)) {
        const same = fs.readFileSync(path.join(ROOT, f), 'utf8') === t;
        if (!same) { diff++; if (!check) fs.writeFileSync(path.join(ROOT, f), t); console.log((check ? 'DIFFERS ' : 'wrote ') + f); }
    }
    console.log(`${Object.keys(out).length} pages, ${diff} ${check ? 'difference(s)' : 'changed'}`);
    process.exit(check && diff ? 1 : 0);
}
